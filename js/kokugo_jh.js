let _kokugoJhLast = '';

function generateKokugoJHProblem(grade, diff = 1) {
  const all = KOKUGO_JH[grade] || KOKUGO_JH[8];
  // やさしい：むずかしめ(h)を のぞく／ふつう：ぜんぶ／むずかしい：むずかしめ ＋ 書き取り ＋ 文法
  let pool = all.filter(it => diff === 0 ? !it.h : (diff === 2 ? (it.h || it.k === 'w' || it.k === 'g') : true));
  if (pool.length < 10) pool = all;
  let it;
  for (let i = 0; i < 6; i++) {
    it = pool[randInt(0, pool.length - 1)];
    if (it.q !== _kokugoJhLast) break;
  }
  _kokugoJhLast = it.q;
  // ひとこと解説が 空の ものは、「ことば ＝ 意味」の 形で おぎなう
  const word = (it.q.match(/「([^」]+)」/) || [])[1];
  const fallback = it.k === 'y' && word ? `「${word}」＝ ${it.a}` : `答え：${it.a}`;
  return {
    question: it.q,
    type: 'choice',
    choices: shuffleArray([it.a, ...it.d]),
    answer: it.a,
    noRead: it.k === 'r',                                   // 読みを たずねる もんだいは、よみあげると 答えが 分かるので しない
    key: `${grade}:${it.k}:${it.q}`.slice(0, 50),
    unitLabel: KOKUGO_LABEL[it.k] || '国語',
    explain: it.ex || fallback
  };
}
