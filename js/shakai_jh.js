let _shakaiJhLast = '';

function generateShakaiJHProblem(grade, diff = 1) {
  const all = SHAKAI_JH[grade] || SHAKAI_JH[8];
  let pool = all.filter(it => diff === 0 ? !it.h : (diff === 2 ? it.h : true));
  if (pool.length < 10) pool = all;
  let it;
  for (let i = 0; i < 6; i++) {
    it = pool[randInt(0, pool.length - 1)];
    if (it.q !== _shakaiJhLast) break;
  }
  _shakaiJhLast = it.q;
  return {
    question: it.q,
    type: 'choice',
    choices: shuffleArray([it.a, ...it.d]),
    answer: it.a,
    key: `${grade}:${it.cat}:${it.q}`.slice(0, 50),
    unitLabel: SHAKAI_LABEL[it.cat] || '社会',
    explain: it.ex || `答え：${it.a}`
  };
}
